create or replace function public.create_like_notification()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.user_id = new.liked_user_id then
    return new;
  end if;

  if exists (select 1 from public.notifications n where n.user_id = new.liked_user_id and n.actor_id = new.user_id and n.type = 'like' and n.related_id = new.id) then
    return new;
  end if;

  insert into public.notifications (user_id, actor_id, type, body, related_id)
  values (
    new.liked_user_id,
    new.user_id,
    'like',
    'Поставил(а) вам лайк 💗',
    new.id
  );

  return new;
end;
$$;

drop trigger if exists likes_notification_trigger on public.likes;
create trigger likes_notification_trigger
after insert on public.likes
for each row execute function public.create_like_notification();

create or replace function public.create_message_notification()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  match_row public.matches%rowtype;
  recipient_id uuid;
  preview text;
begin
  select m.*
    into match_row
    from public.matches m
    join public.conversations c on c.match_id = m.id
   where c.id = new.conversation_id
   limit 1;

  if match_row.id is null then
    return new;
  end if;

  if match_row.user1_id = new.sender_id then
    recipient_id := match_row.user2_id;
  elsif match_row.user2_id = new.sender_id then
    recipient_id := match_row.user1_id;
  else
    return new;
  end if;

  preview := left(trim(new.body), 120);
  if preview = '' then
    preview := 'Отправил(а) вам сообщение';
  end if;

  if exists (select 1 from public.notifications n where n.user_id = recipient_id and n.actor_id = new.sender_id and n.type = 'message' and n.related_id = new.conversation_id and n.body = preview and n.created_at >= new.created_at - interval '2 seconds' and n.created_at <= new.created_at + interval '2 seconds') then
    return new;
  end if;

  insert into public.notifications (user_id, actor_id, type, body, related_id)
  values (
    recipient_id,
    new.sender_id,
    'message',
    preview,
    new.conversation_id
  );

  return new;
end;
$$;

